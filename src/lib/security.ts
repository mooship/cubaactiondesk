/**
 * Security headers. One definition, used for the Worker's responses (withSecurityHeaders)
 * and written to public/_headers for prerendered pages (npm run build:headers; a test fails if the
 * file drifts). The Content-Security-Policy is not here: Astro writes it per page, with hashes for
 * the inlined CSS (see `security.csp` in astro.config.mjs).
 */
export const SECURITY_HEADERS: Record<string, string> = {
  "Strict-Transport-Security": "max-age=31536000; includeSubDomains",
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
  "Cross-Origin-Opener-Policy": "same-origin",
};

/** Adds the headers to a response, never overriding one the route set on purpose. */
export function withSecurityHeaders(response: Response): Response {
  const headers = new Headers(response.headers);
  for (const [name, value] of Object.entries(SECURITY_HEADERS)) {
    if (!headers.has(name)) headers.set(name, value);
  }
  return new Response(response.body, { status: response.status, statusText: response.statusText, headers });
}

/** Contents of public/_headers: the same headers for every static asset. */
export function headersFile(): string {
  const lines = Object.entries(SECURITY_HEADERS).map(([name, value]) => `  ${name}: ${value}`);
  return `# Generated by scripts/build-headers.ts from src/lib/security.ts. Do not edit by hand.\n/*\n${lines.join("\n")}\n`;
}
